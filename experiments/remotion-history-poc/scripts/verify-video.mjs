import {spawnSync} from 'node:child_process';
import {existsSync} from 'node:fs';
const filename='out/history-poc.mp4';
if(!existsSync(filename))throw Error('Missing '+filename);
const p=spawnSync('ffprobe',['-v','error','-count_frames','-select_streams','v:0','-show_entries','stream=codec_name,width,height,r_frame_rate,nb_read_frames:format=duration','-of','json',filename],{encoding:'utf8'});
if(p.status!==0)throw Error(p.stderr);
const meta=JSON.parse(p.stdout);const stream=meta.streams?.[0];const d=Number(meta.format?.duration);
const ok=stream?.codec_name==='h264'&&stream?.width===1920&&stream?.height===1080&&stream?.r_frame_rate==='30/1'&&Number(stream?.nb_read_frames)===1800&&Math.abs(d-60)<0.02;
if(!ok)throw Error('H264 metadata mismatch: '+JSON.stringify(meta));
const dec=spawnSync('ffmpeg',['-v','error','-i',filename,'-f','null','-'],{encoding:'utf8'});
if(dec.status!==0)throw Error('Decode failed '+dec.stderr);
console.log(JSON.stringify({status:'PASS',file:filename,codec:stream.codec_name,width:stream.width,height:stream.height,fps:stream.r_frame_rate,frames:stream.nb_read_frames,duration:d,fullDecode:'PASS'}));
